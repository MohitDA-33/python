# To write strings we use single quotes('), double quotes("), or triple quotes(''' or """), it yields the same results.

# Example:

# Single quotes string:
a = 'Hello world!'
print(a)

# Double quotes string:
b = "Hello! python"
print(b)

# You can't write a multi-line string in a single/double quotes. if you try you can't do that. use escape sequence character.
# If you are sure that your string is going to be a single line use single/double quotes.

# Triple quotes string (useful for multi line string):
c='''This is a
multi-line
string'''
print(c)

d = """This is also 
a multi-line 
string, but using a 
triple double quotes"""
print(d)

# Note: triple quotes is used for comments and multi line strings