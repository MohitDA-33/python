# Tuple methods and operations

# Tuples unlike lists dont have a lot of operations or methods, cause is immutable/unchangeable.

# Common tuple methods:

tu = (10, 20, 31, 40, 10, 51, 40)

print(tu.count(10))   # Will return the number of times 10 appears, which is 2.
print(tu.index(40))   # It will give the index of the first occurance of 40.